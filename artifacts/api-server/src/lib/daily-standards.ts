const DAILY_STANDARD_JOB = "daily-standard-rollover";
const STANDARD_FAILURE_BACKFILL_JOB = "standard-failure-warning-backfill-v1";
const assignmentIssuer = alias(membersTable, "daily_standard_assignment_issuer");
type DailyStandardTransaction = Parameters<Parameters<typeof db.transaction>[0]>[0];
type DailyStandard = typeof standardsTable.$inferSelect;

function moscowDateLabel(date: Date): string {
  return new Intl.DateTimeFormat("ru-RU", {
    timeZone: MOSCOW_TIME_ZONE,
    day: "numeric",
    month: "long",
    year: "numeric",
  }).format(date);
}

async function assignDailyStandards(
  tx: DailyStandardTransaction,
  standards: DailyStandard[],
  now: Date,
  trigger: "saved" | "rollover" | "inactivity_cancelled",
  options: { memberId?: string; inactivityRequestId?: string } = {},
) {
  const cycle = getMoscowDailyCycle(now);
  const activeStandards = standards.filter(
    (standard) =>
      standard.dailyEnabled && standard.dailyRank && !standard.archivedAt,
  );
  if (activeStandards.length === 0) return 0;

  const activeMembers = await tx
    .select({
      id: membersTable.id,
      nickname: membersTable.nickname,
      role: membersTable.role,
      rank: membersTable.rank,
    })
    .from(membersTable)
    .where(
      and(
        eq(membersTable.status, "active"),
        options.memberId ? eq(membersTable.id, options.memberId) : undefined,
      ),
    );
  const membersWithTitles = activeMembers.map((member) => ({
    ...member,
    title: titleForMember(member.role, member.rank),
  }));
  const approvedInactivityPeriods = activeMembers.length
    ? await tx
        .select({
          memberId: inactivityRequestsTable.memberId,
          startDate: inactivityRequestsTable.startDate,
          endDate: inactivityRequestsTable.endDate,
        })
        .from(inactivityRequestsTable)
        .where(
          and(
            eq(inactivityRequestsTable.status, "approved"),
            inArray(
              inactivityRequestsTable.memberId,
              activeMembers.map((member) => member.id),
            ),
          ),
        )
    : [];
  const inactiveMemberIds = new Set(
    approvedInactivityPeriods
      .filter((period) =>
        isDateWithinInactivityPeriod(cycle.dayKey, period),
      )
      .map((period) => period.memberId),
  );
  let assignedCount = 0;

  for (const activeStandard of activeStandards) {
    const [issuer] = await tx
      .select({ nickname: membersTable.nickname })
      .from(membersTable)
      .where(eq(membersTable.id, activeStandard.createdById))
      .limit(1);
    const eligibleMembers = membersWithTitles.filter(
      (member) =>
        !inactiveMemberIds.has(member.id) &&
        isDailyStandardPosition(member.title) &&
        normalizeDailyStandardRank(member.title) ===
          normalizeDailyStandardRank(activeStandard.dailyRank!),
    );

    for (const member of eligibleMembers) {
      const [existingAssignment] = await tx
        .select({
          id: standardAssignmentsTable.id,
          status: standardAssignmentsTable.status,
        })
        .from(standardAssignmentsTable)
        .where(
          and(
            eq(standardAssignmentsTable.standardId, activeStandard.id),
            eq(standardAssignmentsTable.assigneeId, member.id),
            eq(standardAssignmentsTable.dueAt, cycle.endsAt),
            eq(standardAssignmentsTable.autoGenerated, true),
            isNull(standardAssignmentsTable.cycleClosedAt),
          ),
        )
        .limit(1);
      if (existingAssignment) {
        if (
          trigger === "inactivity_cancelled" &&
          existingAssignment.status === "cancelled"
        ) {
          const [cancelledAssignment] = await tx
            .select({ id: standardAssignmentsTable.id })
            .from(standardAssignmentsTable)
            .where(eq(standardAssignmentsTable.id, existingAssignment.id))
            .for("update");

          if (cancelledAssignment) {
            const [latestSubmission] = await tx
              .select({ status: standardSubmissionsTable.status })
              .from(standardSubmissionsTable)
              .where(
                eq(standardSubmissionsTable.assignmentId, cancelledAssignment.id),
              )
              .orderBy(desc(standardSubmissionsTable.version))
              .limit(1);
            const restoredStatus =
              latestSubmission?.status === "pending_review" ||
              latestSubmission?.status === "revision_required"
                ? latestSubmission.status
                : "not_submitted";
            const [restored] = await tx
              .update(standardAssignmentsTable)
              .set({ status: restoredStatus })
              .where(
                and(
                  eq(standardAssignmentsTable.id, cancelledAssignment.id),
                  eq(standardAssignmentsTable.status, "cancelled"),
                  isNull(standardAssignmentsTable.cycleClosedAt),
                ),
              )
              .returning({ id: standardAssignmentsTable.id });

            if (restored) {
              assignedCount += 1;
              const deadline = new Intl.DateTimeFormat("ru-RU", {
                timeZone: MOSCOW_TIME_ZONE,
                day: "numeric",
                month: "long",
                year: "numeric",
              }).format(cycle.endsAt);
              await tx.insert(notificationsTable).values({
                recipientId: member.id,
                kind: "standard_assigned",
                title: "Дневной норматив восстановлен",
                message: `${activeStandard.title} снова доступен после аннулирования неактива. Срок до 23:59 МСК ${deadline}.`,
                relatedType: "standard_assignment",
                relatedId: restored.id,
              });
              await writeAudit(tx, {
                actorId: activeStandard.createdById,
                actorNickname: issuer?.nickname ?? "Лидер",
                category: "standards",
                action: "standard.daily_restored_after_inactivity_cancellation",
                entityType: "standard_assignment",
                entityId: restored.id,
                entityLabel:
                  "Восстановлен дневной норматив после аннулирования неактива: " +
                  activeStandard.title + " → " + member.nickname,
                targetMemberId: member.id,
                targetMemberNickname: member.nickname,
                details: {
                  automatic: true,
                  trigger,
                  inactivityRequestId: options.inactivityRequestId,
                  day: cycle.dayKey,
                  restoredStatus,
                  dueAt: cycle.endsAt,
                  standardId: activeStandard.id,
                },
              });
            }
          }
        }
        continue;
      }

      const [created] = await tx
        .insert(standardAssignmentsTable)
        .values({
          standardId: activeStandard.id,
          assigneeId: member.id,
          assignedById: activeStandard.createdById,
          dueAt: cycle.endsAt,
          status: "not_submitted",
          autoGenerated: true,
        })
        .returning({ id: standardAssignmentsTable.id });
      if (!created) continue;

      assignedCount += 1;
      const deadline = new Intl.DateTimeFormat("ru-RU", {
        timeZone: MOSCOW_TIME_ZONE,
        day: "numeric",
        month: "long",
        year: "numeric",
      }).format(cycle.endsAt);
      await tx.insert(notificationsTable).values({
        recipientId: member.id,
        kind: "standard_assigned",
        title:
          trigger === "inactivity_cancelled"
            ? "Назначен норматив после аннулирования неактива"
            : "Назначен дневной норматив",
        message:
          trigger === "inactivity_cancelled"
            ? `${activeStandard.title} назначен после аннулирования неактива. Срок до 23:59 МСК ${deadline}.`
            : `${activeStandard.title} — срок до 23:59 МСК ${deadline}.`,
        relatedType: "standard_assignment",
        relatedId: created.id,
      });
      await writeAudit(tx, {
        actorId: activeStandard.createdById,
        actorNickname: issuer?.nickname ?? "Лидер",
        category: "standards",
        action:
          trigger === "inactivity_cancelled"
            ? "standard.daily_assigned_after_inactivity_cancellation"
            : "standard.daily_assigned",
        entityType: "standard_assignment",
        entityId: created.id,
        entityLabel: `Ежедневный норматив: ${activeStandard.title} → ${member.nickname}`,
        targetMemberId: member.id,
        targetMemberNickname: member.nickname,
        details: {
          automatic: true,
          trigger,
          inactivityRequestId: options.inactivityRequestId,
          day: cycle.dayKey,
          rank: member.title,
          dueAt: cycle.endsAt,
          standardId: activeStandard.id,
        },
      });
    }
  }

  return assignedCount;
}

export async function restoreDailyStandardsAfterInactivityCancellation(
  tx: DailyStandardTransaction,
  memberId: string,
  inactivityRequestId: string,
  now = new Date(),
) {
  const activeStandards = await tx
    .select()
    .from(standardsTable)
    .where(
      and(
        eq(standardsTable.dailyEnabled, true),
        isNull(standardsTable.archivedAt),
      ),
    )
    .orderBy(desc(standardsTable.createdAt))
    .for("update");

  return assignDailyStandards(
    tx,
    activeStandards,
    now,
    "inactivity_cancelled",
    { memberId, inactivityRequestId },
  );
}

export async function assignDailyStandardImmediately(
  tx: DailyStandardTransaction,
  standard: DailyStandard,
  now = new Date(),
) {
  return assignDailyStandards(tx, [standard], now, "saved");
}

async function backfillRejectedStandardWarnings(
  tx: DailyStandardTransaction,
  now: Date,
): Promise<number> {
  const [claim] = await tx
    .insert(systemJobStateTable)
    .values({ jobName: STANDARD_FAILURE_BACKFILL_JOB, lastRunAt: now })
    .onConflictDoNothing()
    .returning({ jobName: systemJobStateTable.jobName });
  if (!claim) return 0;

  const rejectedSubmissions = await tx
    .select({
      assignmentId: standardAssignmentsTable.id,
      memberId: standardAssignmentsTable.assigneeId,
      assignedById: standardAssignmentsTable.assignedById,
      assignedByNickname: assignmentIssuer.nickname,
      standardTitle: standardsTable.title,
      reason: standardSubmissionsTable.decisionReason,
    })
    .from(standardSubmissionsTable)
    .innerJoin(
      standardAssignmentsTable,
      eq(standardSubmissionsTable.assignmentId, standardAssignmentsTable.id),
    )
    .innerJoin(standardsTable, eq(standardAssignmentsTable.standardId, standardsTable.id))
    .innerJoin(membersTable, eq(standardAssignmentsTable.assigneeId, membersTable.id))
    .innerJoin(assignmentIssuer, eq(standardAssignmentsTable.assignedById, assignmentIssuer.id))
    .where(inArray(standardSubmissionsTable.status, ["rejected", "revision_required"]))
    .orderBy(asc(standardSubmissionsTable.reviewedAt), asc(standardSubmissionsTable.submittedAt));

  let issuedCount = 0;
  for (const rejected of rejectedSubmissions) {
    const reason = formatStandardFailureReason(
      rejected.standardTitle,
      "отклонён. Причина проверки: " + (rejected.reason?.trim() || "Отчёт по нормативу отклонён руководителем."),
    );
    const issue = await issueStandardFailureDiscipline(tx, {
      assignmentId: rejected.assignmentId,
      memberId: rejected.memberId,
      assignedById: rejected.assignedById,
      assignedByNickname: rejected.assignedByNickname,
      standardTitle: rejected.standardTitle,
      reason,
    });
    if (issue.kind !== "issued") continue;

    issuedCount += 1;
    await tx.insert(notificationsTable).values({
      recipientId: rejected.memberId,
      kind: "standard_reviewed",
      title: issue.type === "warning" ? "Предупреждение за отклонённый норматив" : "Выговор за отклонённый норматив",
      message: reason + (issue.type === "warning"
        ? " Автоматическое предупреждение добавлено в дисциплинарную историю."
        : " Автоматически применено действующее правило конвертации предупреждения в выговор."),
      relatedType: "standard_assignment",
      relatedId: rejected.assignmentId,
    });
  }
  return issuedCount;
}

export async function runDailyStandardCycle(now = new Date()) {
  const cycle = getMoscowDailyCycle(now);

  return db.transaction(async (tx) => {
    const backfilledWarningCount = await backfillRejectedStandardWarnings(tx, now);
    const [claim] = await tx
      .insert(systemJobStateTable)
      .values({ jobName: DAILY_STANDARD_JOB, lastRunAt: now })
      .onConflictDoUpdate({
        target: systemJobStateTable.jobName,
        set: { lastRunAt: now },
        setWhere: lt(systemJobStateTable.lastRunAt, cycle.startsAt),
      })
      .returning({ jobName: systemJobStateTable.jobName });

    if (!claim) {
      return {
        day: cycle.dayKey,
        alreadyProcessed: true,
        backfilledWarningCount,
        closedCount: 0,
        assignedCount: 0,
      };
    }

    const activeStandards = await tx
      .select()
      .from(standardsTable)
      .where(
        and(
          eq(standardsTable.dailyEnabled, true),
          isNull(standardsTable.archivedAt),
        ),
      )
      .orderBy(desc(standardsTable.createdAt))
      .for("update");

    const expiredAssignments = await tx
      .select({
        id: standardAssignmentsTable.id,
        standardId: standardAssignmentsTable.standardId,
        assigneeId: standardAssignmentsTable.assigneeId,
        assignedById: standardAssignmentsTable.assignedById,
        status: standardAssignmentsTable.status,
        dueAt: standardAssignmentsTable.dueAt,
        title: standardsTable.title,
        assigneeNickname: membersTable.nickname,
        issuerNickname: assignmentIssuer.nickname,
      })
      .from(standardAssignmentsTable)
      .innerJoin(
        standardsTable,
        eq(standardAssignmentsTable.standardId, standardsTable.id),
      )
      .innerJoin(
        membersTable,
        eq(standardAssignmentsTable.assigneeId, membersTable.id),
      )
      .innerJoin(
        assignmentIssuer,
        eq(standardAssignmentsTable.assignedById, assignmentIssuer.id),
      )
      .where(
        and(
          inArray(standardAssignmentsTable.status, ["not_submitted", "pending_review"]),
          isNull(standardAssignmentsTable.cycleClosedAt),
          lte(standardAssignmentsTable.dueAt, cycle.startsAt),
        ),
      );

    for (const assignment of expiredAssignments) {
      const missingSubmission = assignment.status === "not_submitted";
      let version: number | null = null;
      let automaticFailureStatus: "rejected" | null = null;
      if (missingSubmission) {
        const [versionCount] = await tx
          .select({ value: count() })
          .from(standardSubmissionsTable)
          .where(eq(standardSubmissionsTable.assignmentId, assignment.id));
        version = Number(versionCount?.value ?? 0) + 1;
        const message = `Период норматива завершён автоматически ${moscowDateLabel(assignment.dueAt)} в 23:59 МСК. Сдача не отправлена; скриншотов нет.`;
        const failureReason = formatStandardFailureReason(
          assignment.title,
          "не сдан в срок (" + moscowDateLabel(assignment.dueAt) + " до 23:59 МСК).",
        );
        const automaticRejection = createAutomaticStandardRejection({
          version,
          comment: message,
          reason: failureReason,
          submittedAt: now,
        });
        automaticFailureStatus = automaticRejection.status;
        await tx.insert(standardSubmissionsTable).values({
          assignmentId: assignment.id,
          ...automaticRejection,
        });
        const missingPointsDelta = standardPointsDelta("not_submitted");
        const missingPointsRecorded = await recordPointChange(tx, {
          memberId: assignment.assigneeId,
          memberNickname: assignment.assigneeNickname,
          delta: missingPointsDelta,
          reason: failureReason,
          source: standardPointsSource("not_submitted"),
          assignmentId: assignment.id,
          actorId: assignment.assignedById,
          actorNickname: assignment.issuerNickname,
        });
        const disciplineIssue = await issueStandardFailureDiscipline(tx, {
          assignmentId: assignment.id,
          memberId: assignment.assigneeId,
          assignedById: assignment.assignedById,
          assignedByNickname: assignment.issuerNickname,
          standardTitle: assignment.title,
          reason: failureReason,
        });
        const disciplineNotice = disciplineIssue.kind === "issued"
          ? disciplineIssue.type === "warning"
            ? { title: "Предупреждение за несданный норматив", message: " Автоматически выдано предупреждение." }
            : { title: "Выговор за несданный норматив", message: " Автоматически выдан выговор по действующим правилам дисциплины." }
          : disciplineIssue.kind === "limit"
            ? { title: "Норматив закрыт на проверку", message: " Автоматическое взыскание не назначено из-за действующего дисциплинарного ограничения." }
            : disciplineIssue.kind === "already-issued"
              ? { title: "Норматив закрыт на проверку", message: " Предупреждение за этот норматив уже было зарегистрировано." }
              : { title: "Норматив закрыт на проверку", message: " Автоматическое взыскание не назначено: сотрудник неактивен." };
        await tx.insert(notificationsTable).values({
          recipientId: assignment.assigneeId,
          kind: "standard_auto_closed",
          title: disciplineNotice.title,
          message: message + disciplineNotice.message + (missingPointsRecorded ? " Списано 2 балла за несданный норматив." : ""),
          relatedType: "standard_assignment",
          relatedId: assignment.id,
        });
      }
      await tx
        .update(standardAssignmentsTable)
        .set({
          ...(automaticFailureStatus ? { status: automaticFailureStatus } : {}),
          cycleClosedAt: now,
        })
        .where(eq(standardAssignmentsTable.id, assignment.id));
      await writeAudit(tx, {
        actorId: assignment.assignedById,
        actorNickname: assignment.issuerNickname,
        category: "standards",
        action: "standard.daily_closed",
        entityType: "standard_assignment",
        entityId: assignment.id,
        entityLabel: `Автоматически закрыт норматив: ${assignment.title}`,
        targetMemberId: assignment.assigneeId,
        targetMemberNickname: assignment.assigneeNickname,
        details: {
          automatic: true,
          day: cycle.dayKey,
          statusBeforeClose: assignment.status,
          submissionVersion: version,
          submittedWithEvidence: !missingSubmission,
        },
      });
    }

    if (activeStandards.length === 0) {
      return {
        day: cycle.dayKey,
        alreadyProcessed: false,
        dailyStandardEnabled: false,
        backfilledWarningCount,
        closedCount: expiredAssignments.length,
        assignedCount: 0,
      };
    }

    const assignedCount = await assignDailyStandards(
      tx,
      activeStandards,
      now,
      "rollover",
    );

    return {
      day: cycle.dayKey,
      alreadyProcessed: false,
      dailyStandardEnabled: true,
      backfilledWarningCount,
      closedCount: expiredAssignments.length,
      assignedCount,
    };
  });
}
